"""Register stopped candidate workers on a Vast Linux instance, without SAM."""

import platform
import shlex
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MODELS = tuple(
    f"{family}-{size}" for family in ("yolov8", "yolo26", "rfdetr") for size in "nsml"
)


def main():
    if platform.system() != "Linux" or not Path("/opt/supervisor-scripts").is_dir():
        raise SystemExit("Run this only inside the prepared Vast Linux instance.")
    python = ROOT / ".venv-seg-benchmark/bin/python"
    if not python.is_file():
        raise SystemExit("Run setup.sh seg first.")
    logs = ROOT / "outputs/worker-logs"
    logs.mkdir(parents=True, exist_ok=True)
    wrapper = Path("/opt/supervisor-scripts/goodvision-seg.sh")
    wrapper.write_text(
        "#!/bin/bash\nset -euo pipefail\n"
        'case "${1:-}" in\n'
        "  yolov8-[nsml]|yolo26-[nsml]|rfdetr-[nsml]) ;;\n"
        "  *) exit 2 ;;\nesac\n"
        f"cd {shlex.quote(str(ROOT))}\n"
        "export PYTHONUNBUFFERED=1 PYTHON_DOTENV_DISABLED=1\n"
        f"{shlex.quote(str(python))} -m tools.seg_pipeline.worker "
        '--model "$1" --port 8092 2>&1 | '
        f'tee -a {shlex.quote(str(logs))}/"$1".log\n'
    )
    wrapper.chmod(0o755)
    sections = ["# Generated by tools/vast_benchmark/install_services.py\n"]
    for model in MODELS:
        sections.append(
            f"[program:seg-{model}]\n"
            f"command={wrapper} {model}\n"
            f"directory={ROOT}\n"
            "environment=PYTHONUNBUFFERED=\"1\",PYTHON_DOTENV_DISABLED=\"1\"\n"
            "autostart=false\nautorestart=false\nstartsecs=2\nstartretries=0\n"
            "stopasgroup=true\nkillasgroup=true\nstopwaitsecs=20\n"
            "stdout_logfile=/dev/stdout\nstdout_logfile_maxbytes=0\n"
            "redirect_stderr=true\n"
        )
    sections.append(
        "[group:goodvision-seg]\nprograms="
        + ",".join(f"seg-{model}" for model in MODELS)
        + "\n"
    )
    Path("/etc/supervisor/conf.d/goodvision-seg.conf").write_text("\n".join(sections))
    subprocess.run(["supervisorctl", "reread"], check=True)
    subprocess.run(["supervisorctl", "update", "goodvision-seg"], check=True)
    print("Registered 12 candidate workers; autostart is disabled.")


if __name__ == "__main__":
    main()
