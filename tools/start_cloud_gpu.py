"""Launch a local gateway and N analysis lanes on the rented GPU host.

This launcher does not rent GPUs. Choose the hardware and press Start in the UI.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
from pathlib import Path

if __package__:
    from . import start_modular as modular
else:
    import start_modular as modular

ROOT = Path(__file__).resolve().parents[1]


def fleet_overlay(streams):
    streams = modular.positive_integer(streams, "--streams")
    environment = {"SAM31_LIVE_CAMERAS": str(streams)}
    for index in range(1, streams + 1):
        key = f"LOCAL_CAMERA_{index:02d}_STREAM_URL"
        environment[key] = "${" + key + ":-}"
    volumes = [
        f"camera-{index:02d}-data:/legacy/camera-{index:02d}:ro"
        for index in range(1, streams + 1)
    ]
    return (
        "# Generated by tools/start_cloud_gpu.py\n"
        "services:\n  sam-remote:\n    environment: "
        + json.dumps(environment)
        + "\n    volumes: "
        + json.dumps(volumes)
        + "\nvolumes:\n"
        + "".join(
            f"  camera-{index:02d}-data: {{}}\n" for index in range(1, streams + 1)
        )
    )


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--streams",
        type=int,
        default=1,
        help="Video lane count, without a product limit",
    )
    parser.add_argument("--env-file", type=Path)
    parser.add_argument("--no-build", action="store_true")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)
    try:
        streams = modular.positive_integer(args.streams, "--streams")
        env_file = args.env_file.resolve() if args.env_file else ROOT / ".env"
        if args.env_file and not env_file.is_file():
            raise ValueError("Environment file does not exist")
        destination = ROOT / ".goodvision/cloud-compose.yaml"
        overlay = fleet_overlay(streams)
        command = ["docker", "compose", "--project-directory", str(ROOT)]
        if env_file.is_file():
            command.extend(["--env-file", str(env_file)])
        command.extend(
            [
                "-f",
                str(ROOT / "compose.cloud-gpu.yaml"),
                "-f",
                str(destination),
                "up",
                "--detach",
                "--wait",
                "--wait-timeout",
                "900",
            ]
        )
        if not args.no_build:
            command.append("--build")
        command.extend(
            [
                "sam-remote",
                "harness",
            ]
        )
        print(
            json.dumps(
                {
                    "streams": streams,
                    "analysis_location": "gpu_host",
                    "command": command,
                    "fleet_overlay": overlay,
                    "rental": "Start explicitly from the cloud GPU panel",
                },
                indent=2,
            )
        )
        if args.dry_run:
            return 0
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(overlay, encoding="utf-8")
        return subprocess.run(
            command,
            cwd=ROOT,
            env=dict(os.environ, HARNESS_FLEET_CAPACITY=str(streams)),
            check=False,
        ).returncode
    except (OSError, ValueError) as error:
        print(f"Cloud console setup failed: {error}")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
