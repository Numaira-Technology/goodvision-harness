"""Emit a batch run plan for a whole Benchmark V1 question set.

The README documents the manual per-video flow (assemble -> publish -> capture)
for the 2-video sample. For the 80-question diversity set that is 74 videos, so
this generates a single ready-to-run bash script that repeats the documented
steps for every media item, in source order, reusing one harness session.

It is a *plan generator*, not a new ingestion path: every line it emits is a
command the README already defines (`replay/*.sh`, `bench.capture_live`). Review
the script, then run it on the GPU host. `bench.run_bench` then joins the
captures to predictions.

Per video the plan:
  1. image_sequence -> assemble frames to <video_id>.mp4 at the manifest fps;
     file -> use the downloaded file directly.
  2. publish it to RTSP path `bench` (offline single-pass; scoring must not loop).
  3. point the harness session (SCENE_ENGINE_MODE=active, PERSON_TRACKING_ENABLED)
     at rtsp://localhost:8554/bench  -- the one operator-supplied step.
  4. capture_live polls the session -> caps/<video_id>.json.

Usage:
    python -m bench.run_batch --media ../bench_v1_sample80/media.jsonl \
        --media-root /data/benchmark_v1 --base-url http://127.0.0.1:7900 \
        --caps caps --out run_batch.sh
    bash run_batch.sh                 # on the GPU host
    python -m bench.run_bench --questions ../bench_v1_sample80/questions.jsonl \
        --media ../bench_v1_sample80/media.jsonl --captures caps --output predictions.jsonl
"""

from __future__ import annotations

import argparse
from pathlib import Path

from .manifest import fps_by_video
from .schema import load_jsonl, load_questions

_REPLAY = "benchmark/replay"


def plan_video(
    row: dict,
    fps: float | None,
    media_root: str,
    base_url: str,
    caps_dir: str,
    path_name: str = "bench",
    session_start_cmd: str = "",
    session_stop_cmd: str = "",
) -> list[str]:
    """Shell lines that capture one media item in an ISOLATED session. Pure; tested.

    Per video: snapshot the current session id, (re)start a fresh harness session
    on the stream, publish the file paced at source rate (single pass), capture
    only that new session's data, then stop publisher and session. This keeps each
    video's tracks/events from bleeding into the next video's capture.
    """
    vid = row["video_id"]
    md = row["media"]
    src = f"{media_root.rstrip('/')}/{md['path_or_name']}"
    stream_url = f"rtsp://localhost:8554/{path_name}"
    lines = [f"echo '=== {vid} ({row['source_dataset']}, {md['media_type']}) ==='"]

    if md["media_type"] == "image_sequence":
        clip = f'"$WORK/{vid}.mp4"'  # double-quoted so $WORK expands, colons safe
        rate = fps or 25.0
        lines.append(f"{_REPLAY}/assemble_frames.sh '{src}' {clip} {rate:g}")
        feed = clip
    else:
        feed = f"'{src}'"

    def sub(cmd: str) -> str:
        return (cmd.replace("{stream_url}", stream_url)
                   .replace("{video_id}", vid).replace("{path}", path_name))

    # Baseline session id BEFORE publishing, so capture can require a fresh one.
    lines.append(f'BASE=$(python -m bench.capture_live --print-session --base-url {base_url})')
    if session_start_cmd:
        lines.append(sub(session_start_cmd))
    lines += [
        # -re single pass: wall-clock ~= source seconds (see publish script header).
        f"{_REPLAY}/publish_rtsp_realtime_once.sh {feed} {path_name} & PUB=$!",
        f"python -m bench.capture_live --base-url {base_url} --video-id {vid} "
        f'--require-session-change-from "$BASE" --out {caps_dir}/{vid}.json',
        "kill $PUB 2>/dev/null || true",
        "wait $PUB 2>/dev/null || true",
    ]
    if session_stop_cmd:
        lines.append(sub(session_stop_cmd))
    return lines


def build_script(
    media_rows: list[dict],
    fps: dict[str, float],
    media_root: str,
    base_url: str,
    caps_dir: str,
    session_start_cmd: str = "",
    session_stop_cmd: str = "",
) -> str:
    head = [
        "#!/usr/bin/env bash",
        "# Generated by bench.run_batch. Review before running on the GPU host.",
        "# Prereqs: MediaMTX up; the harness in active scene mode",
        "#   (SCENE_ENGINE_MODE=active PERSON_TRACKING_ENABLED=true).",
        "# Each video runs in an ISOLATED session: pass --session-start-cmd /",
        "#   --session-stop-cmd so a fresh session ingests rtsp://localhost:8554/bench",
        "#   per video. If your harness auto-starts a session on each new RTSP",
        "#   connection, session gating (--require-session-change-from) still keeps",
        "#   captures from mixing. Run from the repo root.",
        "set -euo pipefail",
        'WORK="$(mktemp -d)"',
        f"mkdir -p {caps_dir}",
        "",
    ]
    body: list[str] = []
    for row in media_rows:
        body += plan_video(row, fps.get(row["video_id"]), media_root, base_url, caps_dir,
                           session_start_cmd=session_start_cmd, session_stop_cmd=session_stop_cmd)
        body.append("")
    tail = [f"echo 'captures written to {caps_dir}/ — now run bench.run_bench'"]
    return "\n".join(head + body + tail) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--media", type=Path, required=True)
    ap.add_argument("--questions", type=Path, help="optional: only for fps derivation")
    ap.add_argument("--media-root", default="/data/benchmark_v1",
                    help="local root the media paths resolve under")
    ap.add_argument("--base-url", default="http://127.0.0.1:7900")
    ap.add_argument("--caps", default="caps", help="capture output dir")
    ap.add_argument("--session-start-cmd", default="",
                    help="per-video command to start a fresh harness session; "
                         "placeholders {stream_url} {video_id} {path}")
    ap.add_argument("--session-stop-cmd", default="",
                    help="per-video command to stop the session; same placeholders")
    ap.add_argument("--out", type=Path, help="write the plan script (default: stdout)")
    args = ap.parse_args(argv)

    media_rows = list(load_jsonl(args.media))
    fps = fps_by_video(load_questions(args.questions)) if args.questions else {}
    script = build_script(media_rows, fps, args.media_root, args.base_url, args.caps,
                          session_start_cmd=args.session_start_cmd,
                          session_stop_cmd=args.session_stop_cmd)
    if args.out:
        args.out.write_text(script, encoding="utf-8")
        args.out.chmod(0o755)
        print(f"[run_batch] wrote {args.out} for {len(media_rows)} videos")
    else:
        print(script, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
